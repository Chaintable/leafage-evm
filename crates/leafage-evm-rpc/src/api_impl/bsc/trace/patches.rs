pub(crate) fn find(
    patches: &'static [StoragePatch],
    tx_hash: &B256,
) -> Option<&'static StoragePatch> {
    patches.iter().find(|patch| patch.tx_hash == *tx_hash)
}

impl StoragePatch {
    pub(crate) fn slots(&self) -> impl Iterator<Item = (U256, U256)> + '_ {
        self.storage.iter().map(|(slot, value)| {
            (
                slot.parse().expect("valid patch slot"),
                value.parse().expect("valid patch value"),
            )
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn patches_parse() {
        let counts: Vec<_> = PATCHES_BEFORE_TX
            .iter()
            .chain(PATCHES_AFTER_TX)
            .map(|p| p.slots().count())
            .collect();
        assert_eq!(counts, vec![11, 22, 7, 22]);
    }
}
